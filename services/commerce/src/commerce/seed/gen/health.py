def N(serving: str, cal: int, fat: float, sat: float, sodium: int, carbs: float, fiber: float,
      sugar: float, added: float, protein: float) -> Nutrition:  # fmt: skip
    return Nutrition(serving, cal, fat, sat, sodium, carbs, fiber, sugar, added, protein)


def zero(serving: str) -> Nutrition:
    """Pills and capsules: nothing to declare beyond the vitamins themselves."""
    return N(serving, 0, 0, 0, 0, 0, 0, 0, 0, 0)


def counts(unit: str, *rows: tuple[int, float]) -> list[Size]:
    """Bottle sizes from (count, dollars) rows, e.g. counts("tablets", (100, 9.99))."""
    return [Size(f"{n}CT", f"{n} {unit}", cents(price)) for n, price in rows]


def supp(
    brand: str,
    product_type: str,
    title: str,
    sizes: list[Size],
    nutrition: Nutrition,
    ingredients: str,
    intro: str,
    specs: dict[str, str],
    *,
    allergens: Iterable[str] = (),
    tags: Iterable[str] = (),
    claims: Iterable[str] = (),
    storage: str = PANTRY,
) -> ProductSeed:
    return food(
        category=CAT, product_type=product_type, brand=brand, title=title, sizes=sizes,
        nutrition=nutrition, ingredients=ingredients, allergens=allergens, tags=tags,
        claims=claims, specs=specs, intro=intro, storage=storage,
    )  # fmt: skip


def device(
    brand: str,
    product_type: str,
    title: str,
    description: str,
    sizes: list[Size],
    tags: Iterable[str] = (),
    specs: dict[str, str] | None = None,
) -> ProductSeed:
    return item(
        category=CAT, product_type=product_type, brand=brand, title=title,
        description=description, sizes=sizes, tags=tags, specs=specs,
    )  # fmt: skip


def one(dollars: float, label: str = "Each", code: str = "EA") -> list[Size]:
    return [Size(code, label, cents(dollars))]


